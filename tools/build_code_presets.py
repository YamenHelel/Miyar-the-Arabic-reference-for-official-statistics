#!/usr/bin/env python3
"""Build code/presets/countries.json from the quote-backed `measures` of the unemployment-rate indicator.

Only numbers read from verified or pasted official texts are written. A field that no quotation states stays null,
and the code library then falls back to the ILO default (and says so). Each preset names the quote it comes from.
"""
import json

from common import CONTENT_DIR, ROOT, load_yaml, quotes_by_slot

ILO_DEFAULT = {"age_min": 15, "search_days": 28, "availability_days": 14, "future_starters": True, "hours_threshold": 35,
               "basis": "ILO 19th ICLS resolution (2013, amended 2023) §47; hours threshold is a national choice — 35 used as a placeholder"}


def main():
    ind = load_yaml(CONTENT_DIR / "indicators" / "ind-unemployment-rate.yml")
    quotes = quotes_by_slot()
    out = {"_default_ilo": ILO_DEFAULT, "_note": "Generated by tools/build_code_presets.py from verified/pasted quotes. Do not edit by hand."}
    intl = ind["international"].get("measures", {})
    out["ilo"] = {"age_min": None, "search_days": intl.get("search_days"),
                  "availability_days": intl.get("availability_days_after_reference_max"),
                  "quote": ind["international"].get("definition_quote"), "status": quotes.get(ind["international"].get("definition_quote"), {}).get("status")}
    for iso, c in ind["countries"].items():
        m = c.get("measures") or {}
        qid = c.get("definition_quote")
        q = quotes.get(qid) or {}
        if q.get("status") not in ("verified", "pasted") or not m:
            continue
        out[iso] = {"age_min": m.get("age_min"), "search_days": m.get("search_days"),
                    "availability_days": m.get("availability_days_after_reference"), "quote": qid, "status": q.get("status"),
                    "source_url": q.get("quoted_from_url", "")}
    path = ROOT / "code" / "presets" / "countries.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(out) - 2} presets -> {path}")


if __name__ == "__main__":
    main()
